import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
test('portfolio : aperçu fidèle, export, saisies protégées et mobile', async ({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('./');
 await page.locator('[data-go="portfolio"]').click();
 await expect(page.locator('#view-portfolio')).toBeVisible();
 await expect(page.locator('.portfolio-document')).toHaveCount(12);
 const card=page.locator('.portfolio-document').filter({has:page.locator('h4', {hasText:'Portfolio et preuves'})}).first();
 await card.locator('summary').click();
 const source=await fs.readFile('livrables-module-02/exemple-fictif-association/07-portfolio/preuves-module-02.md','utf8');
 await expect(card.locator('pre')).toHaveText(source);
 const pending=page.waitForEvent('download');await card.locator('button').click();const file=await pending;
 expect(await fs.readFile(await file.path(),'utf8')).toBe(source);
 await page.locator('#portfolioLoad').click();
 await expect(page.locator('#fV1')).toHaveValue(/Chaque bénévole/);
 await expect(page.locator('#fAttest')).not.toBeChecked();
 await page.locator('#fTitre').fill('Travail à conserver');
 await page.locator('[data-view="portfolio"]').click();
 page.once('dialog',d=>d.dismiss());
 await page.locator('#portfolioLoad').click();
 await expect(page.locator('#fTitre')).toHaveValue('Travail à conserver');
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-view="portfolio"]').click();
 await card.locator('summary').click();await card.locator('summary').click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/portfolio-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'test-results/portfolio-desktop.png',fullPage:true});
 expect(errors).toEqual([]);
});
